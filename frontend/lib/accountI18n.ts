export function useTr() {
  const { locale, dir } = useI18n();
  const t = (key: string) => D[locale][key] ?? D.en[key] ?? key;
  return { t, locale, dir };
}

/** Error codes from the API -> translated message, with a fallback key. */
export function useErrorMessage(prefix: "auth" | "book") {
  const { t } = useTr();
  return (err: unknown) => {
    const code = err instanceof Error ? err.message : "";
    const key = `${prefix}.err.${code}`;
    const msg = t(key);
    return msg === key ? t(`${prefix}.err.generic`) : msg;
  };
}
