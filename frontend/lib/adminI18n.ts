/** `const { t, locale, dir } = useAdminT();` */
export function useAdminT() {
  const { locale, dir, setLocale } = useI18n();
  const t = (key: string) =>
    A[locale][key] ?? (locale !== "en" ? PHRASES[locale][key] : undefined) ?? A.en[key] ?? key;
  return { t, locale, dir, setLocale };
}
